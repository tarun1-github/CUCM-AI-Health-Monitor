"""Hybrid General-Purpose + Cisco CUCM AI Assistant orchestrator with full provenance."""

import time
from typing import Dict, List, Optional

from backend.agents.conversation_manager import (
    ChatMessage,
    ConversationManager,
    LLMProvenance,
    TimingProvenance,
    ToolProvenance,
    get_conversation_manager,
)
from backend.agents.intent_router import IntentRouter
from backend.agents.response_formatter import ResponseFormatter
from backend.ai.provider_manager import get_llm_provider_manager
from backend.integrations.cucm_axl.tool_registry import AXLToolRegistry, get_axl_tool_registry


class CUCMAssistantAgent:
    """Hybrid General AI + Read-Only CUCM Operations assistant with full execution transparency."""

    def __init__(
        self,
        registry: Optional[AXLToolRegistry] = None,
        router: Optional[IntentRouter] = None,
        formatter: Optional[ResponseFormatter] = None,
        conversations: Optional[ConversationManager] = None,
    ):
        self.registry = registry or get_axl_tool_registry()
        self.router = router or IntentRouter()
        self.formatter = formatter or ResponseFormatter()
        self.conversations = conversations or get_conversation_manager()

    def ask(
        self,
        question: str,
        session_id: str = "default",
        execution_preference: str = "auto",  # "auto" | "tool_only"
        mode: str = "auto",  # "auto" | "general" | "cucm"
    ) -> ChatMessage:
        t_start = time.perf_counter()
        mgr = get_llm_provider_manager()
        selected_mode = (mode or "auto").strip().lower()
        if selected_mode not in ("auto", "general", "cucm"):
            selected_mode = "auto"

        allow_llm = execution_preference != "tool_only"
        prior_msgs = self.conversations.get_history(session_id)
        history_ctx: List[Dict[str, str]] = [
            {"role": m.role, "content": m.content[:400]} for m in prior_msgs[-6:]
        ]

        user_msg = ChatMessage(
            session_id=session_id,
            role="user",
            content=question,
            selected_mode=selected_mode,
        )
        self.conversations.add_message(session_id, user_msg)

        stages: List[str] = ["Analyzing intent..."]
        context = self.conversations.get_context(session_id)
        tools = self.registry.list_tools()

        intent = self.router.route(
            question,
            tools,
            context=context,
            allow_llm=allow_llm,
            mode=selected_mode,
            history=history_ctx,
        )

        # 1. CLARIFICATION_REQUIRED
        if intent.intent_type == "CLARIFICATION_REQUIRED" and intent.clarification_question:
            total_ms = round((time.perf_counter() - t_start) * 1000.0, 1)
            reply = ChatMessage(
                session_id=session_id,
                role="assistant",
                content=intent.clarification_question,
                selected_mode=selected_mode,
                intent_type="CLARIFICATION_REQUIRED",
                execution_mode="CLARIFICATION_REQUIRED",
                execution_notice="Clarification requested before executing any CUCM tool.",
                stages=stages,
                ai_available=bool(intent.used_llm),
                ai_provider=intent.llm_provider if intent.used_llm else None,
                llm=LLMProvenance(
                    configured_gateway=mgr.configured_provider,
                    provider=intent.llm_provider or mgr.configured_provider,
                    model=intent.llm_model or mgr.get_active_model(),
                    invocation_success=bool(intent.used_llm),
                    response_generation_success=bool(intent.used_llm),
                ),
                timing=TimingProvenance(llm_latency_ms=intent.llm_latency_ms, total_latency_ms=total_ms),
            )
            self.conversations.add_message(session_id, reply)
            return reply

        # 2. GENERAL_AI (no CUCM tools executed)
        if intent.intent_type == "GENERAL_AI" and selected_mode != "cucm":
            stages.append("Generating General AI response (no CUCM tools used)...")
            gen = self.formatter.format_general_ai(question, history=history_ctx, allow_llm=allow_llm)
            total_llm_ms = round(intent.llm_latency_ms + gen.get("llm_latency_ms", 0.0), 1)
            total_ms = round((time.perf_counter() - t_start) * 1000.0, 1)

            if gen["ai_available"]:
                actual_prov = gen["ai_provider"] or mgr.configured_provider
                actual_mdl = gen["ai_model"] or mgr.get_active_model()
                mgr.record_call_result(True, total_llm_ms, actual_provider=actual_prov, actual_model=actual_mdl)
                exec_mode = "GENERAL_AI"
                notice = f"General AI response generated by {actual_prov} ({actual_mdl}). CUCM tools not used."
            else:
                mgr.record_call_result(False, total_llm_ms, gen.get("llm_error"))
                exec_mode = "LLM_FAILED"
                notice = f"General AI failed ({gen.get('llm_error_category')})."

            reply = ChatMessage(
                session_id=session_id,
                role="assistant",
                content=gen["answer"],
                selected_mode=selected_mode,
                intent_type="GENERAL_AI",
                execution_mode=exec_mode,
                execution_notice=notice,
                tool_used=None,
                source="General AI",
                ai_available=bool(gen["ai_available"]),
                ai_provider=gen.get("ai_provider") if gen["ai_available"] else None,
                llm=LLMProvenance(
                    configured_gateway=mgr.configured_provider,
                    provider=gen.get("ai_provider") or mgr.configured_provider,
                    model=gen.get("ai_model") or mgr.get_active_model(),
                    fallback_used=bool(gen.get("fallback_used")),
                    original_failure=gen.get("original_failure"),
                    failover_history=gen.get("failover_history") or [],
                    invocation_success=bool(gen["ai_available"]),
                    response_generation_success=bool(gen["ai_available"]),
                    error=gen.get("llm_error"),
                    error_category=gen.get("llm_error_category"),
                ),
                tool=ToolProvenance(name=None, success=False, source="Not used"),
                timing=TimingProvenance(llm_latency_ms=total_llm_ms, tool_latency_ms=0.0, total_latency_ms=total_ms),
                stages=stages,
                error=gen.get("llm_error"),
            )
            self.conversations.add_message(session_id, reply)
            return reply

        # 3. CUCM_OPERATION or HYBRID — no tool matched
        if not intent.tool_name:
            total_ms = round((time.perf_counter() - t_start) * 1000.0, 1)
            llm_failed = bool(intent.llm_error)
            mode_out = "LLM_FAILED" if llm_failed else "DETERMINISTIC_FALLBACK"
            notice = (
                f"LLM invocation failed ({intent.llm_error_category}). No matching CUCM tool found."
                if llm_failed
                else "No matching read-only CUCM tool found for this query."
            )
            if llm_failed:
                mgr.record_call_result(False, intent.llm_latency_ms, intent.llm_error)
            reply = ChatMessage(
                session_id=session_id,
                role="assistant",
                content=(
                    "I could not map that question to an approved read-only CUCM tool. "
                    "Try asking about phone registration, unregistered phones, CTI Route Points, "
                    "SIP trunks, Publisher/Subscriber nodes, device pools, or switch to Auto / General AI mode."
                ),
                selected_mode=selected_mode,
                intent_type=intent.intent_type,
                execution_mode=mode_out,
                execution_notice=notice,
                stages=stages,
                ai_available=False,
                llm=LLMProvenance(
                    configured_gateway=mgr.configured_provider,
                    provider=intent.llm_provider or mgr.configured_provider,
                    model=intent.llm_model or mgr.get_active_model(),
                    error=intent.llm_error,
                    error_category=intent.llm_error_category,
                ),
                timing=TimingProvenance(llm_latency_ms=intent.llm_latency_ms, total_latency_ms=total_ms),
                error=intent.llm_error,
            )
            self.conversations.add_message(session_id, reply)
            return reply

        # 4. Execute approved CUCM tool
        spec = self.registry.get_spec(intent.tool_name)
        stages.append(f"Executing {spec.source_api if spec else 'AXL'} ({intent.tool_name})...")
        t_tool = time.perf_counter()
        tool_result = self.registry.execute(intent.tool_name, intent.params)
        tool_ms = round((time.perf_counter() - t_tool) * 1000.0, 1)
        tool_ok = bool(tool_result.get("success", True))

        stages.append("Formatting grounded response...")
        formatted = self.formatter.format(
            question,
            intent.tool_name,
            tool_result,
            allow_llm=allow_llm and intent.used_llm,
            intent_type=intent.intent_type,
            history=history_ctx,
        )

        total_llm_ms = round(intent.llm_latency_ms + formatted.get("llm_latency_ms", 0.0), 1)
        total_ms = round((time.perf_counter() - t_start) * 1000.0, 1)

        llm_err = formatted.get("llm_error") or intent.llm_error
        llm_cat = formatted.get("llm_error_category") or intent.llm_error_category
        actual_prov = formatted.get("ai_provider") or intent.llm_provider or mgr.configured_provider
        actual_mdl = formatted.get("ai_model") or intent.llm_model or mgr.get_active_model()
        gw_fallback_used = bool(formatted.get("fallback_used") or intent.fallback_used)
        orig_failure = formatted.get("original_failure") or intent.original_failure
        failover_hist = formatted.get("failover_history") or intent.failover_history or []

        if execution_preference == "tool_only":
            exec_mode = "TOOL_ONLY"
            notice = "Executed registered CUCM tool directly (Tool-Only mode; no LLM inference performed)."
        elif intent.used_llm and formatted["ai_available"] and tool_ok:
            exec_mode = "HYBRID" if intent.intent_type == "HYBRID" else "LLM_GENERATED"
            notice = (
                f"{'Hybrid' if exec_mode == 'HYBRID' else 'CUCM'} response generated by {actual_prov} ({actual_mdl})"
                + (f" via gateway failover ({orig_failure})." if gw_fallback_used and orig_failure else ".")
            )
            mgr.record_call_result(True, total_llm_ms, actual_provider=actual_prov, actual_model=actual_mdl)
        elif llm_err:
            exec_mode = "DETERMINISTIC_FALLBACK" if tool_ok else "LLM_FAILED"
            notice = (
                f"LLM invocation failed ({llm_cat}). Deterministic fallback was used successfully."
                if tool_ok
                else f"LLM request failed ({llm_cat}) and tool execution failed."
            )
            mgr.record_call_result(False, total_llm_ms, llm_err)
        else:
            exec_mode = "DETERMINISTIC_FALLBACK"
            notice = "This response was generated using deterministic Python logic. No LLM inference was performed."

        if intent.tool_name == "cucm_get_phone" and intent.params.get("device_name"):
            self.conversations.update_context(session_id, {"last_device_name": intent.params["device_name"]})
        elif intent.tool_name == "cucm_list_phones_by_node" and intent.params.get("node_name"):
            self.conversations.update_context(session_id, {"last_node_name": intent.params["node_name"]})

        reply = ChatMessage(
            session_id=session_id,
            role="assistant",
            content=formatted["answer"],
            selected_mode=selected_mode,
            intent_type=intent.intent_type,
            execution_mode=exec_mode,
            execution_notice=notice,
            tool_used=intent.tool_name,
            source=tool_result.get("source") or (spec.source_api if spec else "AXL"),
            ai_available=bool(exec_mode in ("LLM_GENERATED", "HYBRID")),
            ai_provider=actual_prov if exec_mode in ("LLM_GENERATED", "HYBRID") else None,
            llm=LLMProvenance(
                configured_gateway=mgr.configured_provider,
                provider=actual_prov if exec_mode in ("LLM_GENERATED", "HYBRID") else mgr.configured_provider,
                model=actual_mdl if exec_mode in ("LLM_GENERATED", "HYBRID") else mgr.get_active_model(),
                fallback_used=gw_fallback_used,
                original_failure=orig_failure,
                failover_history=failover_hist,
                invocation_success=bool(intent.used_llm),
                response_generation_success=bool(formatted["ai_available"]),
                error=llm_err,
                error_category=llm_cat,
            ),
            tool=ToolProvenance(
                name=intent.tool_name,
                success=tool_ok,
                source=tool_result.get("source") or (spec.source_api if spec else "AXL"),
                error=tool_result.get("error"),
            ),
            timing=TimingProvenance(
                llm_latency_ms=total_llm_ms,
                tool_latency_ms=tool_ms,
                total_latency_ms=total_ms,
            ),
            table=formatted.get("table"),
            stages=stages,
            error=tool_result.get("error") if not tool_ok else llm_err,
        )
        self.conversations.add_message(session_id, reply)
        return reply
